/**
 * `npm run assets:build` — raw model output → shipped sprite strips + catalog entries.
 *
 * Reads `_generated/sheets/`, keys each sheet against its own measured background, detects the frame
 * layout from the pixels, packs a uniform-cell strip, and writes the PNG, the sheet report, the lift
 * profile, and — for every `(slug, action)` pair `catalogTimings.mjs` has a timing rule for
 * (`hasCatalogTiming`) — the catalog row in `public/assets/index.json`. Gated per action, not per
 * slug, because a slug can have timings for only some of its declared actions.
 *
 * ## What this script refuses to do
 *
 * **It never derives the scale.** The scale lives in `public/assets/config/character-bounds.json`,
 * which is tracked and only rewritten deliberately. Vault **A5**: a global constant derived from a
 * single regenerable frame means regenerating that frame silently rescales every other animation and
 * moves every measured bound. Run with `--derive-scale` to compute and print a new one; the build
 * itself will not.
 *
 * **It fails on a missing declared input, and never substitutes** *(vault 4.16)*. `_generated/` is
 * gitignored, so absence is the DEFAULT state on a fresh clone — which is exactly the situation in
 * which a silent fallback ships the wrong art. The vault's evidence is a missing start-image
 * override that quietly substituted the standing idle and produced the worst art defect in that
 * project.
 *
 * **It writes deterministically.** Same inputs, same bytes — `encodePng` uses a **deterministic
 * per-row filter choice** and a fixed deflate level, and every position is integer-rounded. That is
 * what makes the byte-identical rebuild contract *(vault 4.15)* checkable at all.
 *
 * ⚠️ This sentence said *"a fixed filter"* until 2026-08-14, and that stopped being true when
 * `encodePng` gained its adaptive filter. The contract did not change — the choice is a pure
 * function of the pixels, so it is reproducible on any machine — but the stated REASON did, and a
 * contract justified by a false premise is one the next reader will not trust. See `png.mjs`.
 */

import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { decodePng, encodePng } from './png.mjs';
import { auditOrThrow } from './anchorAudit.mjs';
import { dropCastShadow } from './chroma.mjs';
import { packStrip } from './sheets.mjs';
import { gateLoopWrap, gateMotionFloor, summarise, PASS } from './gates.mjs';
import { ACCEPTED_POSE_REPEATS, gateAdjacentDistinct } from './gateAdjacent.mjs';
import { configFor, workListFor, resolveActionScale } from './slugConfig.mjs';
import { hasCatalogTiming, catalogRowFor } from './catalogTimings.mjs';
import { printDerivedScale } from './deriveScale.mjs';
import { decideCatalogRow, liftProfileEntry, sheetReportRow, validateCatalogRows } from './catalogDecision.mjs';
import { upsertCatalogSheets, upsertLiftProfile } from './catalogWrite.mjs';
import { findSource, loadConfig, keySheet, framesOf, sliceFrame, cellPitchFor } from './assetSources.mjs';

/** Where `upsertCatalogSheets` merges this build's rows into. */
const CATALOG_PATH = 'public/assets/index.json';

/**
 * Path/action resolution lives in `slugConfig.mjs` — kept here as a single destructure so this
 * script's own behaviour for `brass-courier` is unchanged, just re-sourced. A later task points
 * this at more than one slug; that rewiring is out of scope here (see `slugConfig.mjs`'s header).
 */
// 🔴 The 4.27 gate, HERE rather than on `assets:build` — `build-assets-all.mjs` spawns this file
// directly and bypassed the script. Full argument in `anchorAudit.mjs`'s header.
auditOrThrow({ label: 'anchor audit (pre-pack)' });

const SLUG = process.argv[2] ?? 'brass-courier';
// `process.argv.slice(3)` is the action filter (work item A-T5) — `--derive-scale` (read again at
// `main()`, line ~148) is a flag, not an action, so it is dropped here rather than fed to
// `workListFor`, which would throw on an unknown action.
const ACTION_ARGS = process.argv.slice(3).filter((a) => !a.startsWith('--'));
const {
  generated: GENERATED,
  outDir: OUT_DIR,
  config: CONFIG,
  liftProfile: LIFT_PROFILE,
  reportPath: REPORT_PATH,
  looping: LOOPING,
} = configFor(SLUG);
const ACTIONS = workListFor(SLUG, ACTION_ARGS).map((item) => item.action);

/** Tracked, and the independent oracle for criterion 4.19 — see where it is written, at the end. */
const LIFT_PROFILE_NOTE =
  'Generated by `npm run assets:build`. Per animation: the sheet contact frame\'s source y ' +
  '(`deepestSourceY`) and each frame\'s own `sourceMaxY`, both measured BEFORE packing, plus the ' +
  '`liftPx` derived from them. Committed on purpose: `_generated/` is gitignored, so this is the ' +
  'only place a test on a clean clone can learn what the source actually contained. Do not ' +
  'hand-edit — regenerate it, and read the diff.';

function main() {
  // A separate command mode that prints and returns before anything is written. `deriveScale.mjs`
  // carries the whole of it, including why the action is an argument rather than a hardcoded
  // 'idle' — and why vault A5 makes this print for a human to paste instead of writing the number.
  if (process.argv.includes('--derive-scale')) {
    printDerivedScale({ slug: SLUG, actions: ACTIONS, generated: GENERATED, configPath: CONFIG });
    return;
  }

  const config = loadConfig(CONFIG);
  const { scale, frameWidth, frameHeight } = config;
  if (!(scale > 0) || !frameWidth || !frameHeight) {
    throw new Error(`assets:build: ${CONFIG} is missing scale/frameWidth/frameHeight`);
  }

  mkdirSync(OUT_DIR, { recursive: true });
  const rows = [];
  const liftProfile = {};
  // Catalog rows this run packed, merged into public/assets/index.json once at the end — see
  // catalogTimings.mjs's header for which slugs are covered.
  const catalogRows = [];
  // Read ONCE, before anything is packed: which keys the shipped catalog already carries. It is the
  // other half of `decideCatalogRow` — a rebuilt sheet with no timing rule is only dangerous when a
  // row for it is already out there.
  const existingCatalogKeys = new Set(
    (JSON.parse(readFileSync(CATALOG_PATH, 'utf8')).sheets ?? []).map((row) => row.key),
  );

  for (const action of ACTIONS) {
    const source = findSource(GENERATED, SLUG, action);
    const { keyed, key, agreement } = keySheet(source);
    /**
     * Per CELL, not per sheet — "below the figure" only means anything inside one frame.
     *
     * Applied to the whole strip first, and it did nothing: `dropCastShadow` compares each blob
     * against the LARGEST component, and on a six-frame sheet that is one particular pose. A shadow
     * under frame 5 is not below the tallest figure on the sheet, so the test never fired while the
     * ellipse stayed visible in the output. Measuring across a boundary the concept does not cross
     * is the same error `assertSingleRowLayout` guards on the other axis.
     */
    // `cellPitchFor` returns null for any strip extracted before build-clips started declaring its
    // geometry, which keeps those on the original `detectFrames` path — so introducing this cannot
    // repack shipped art behind anyone's back.
    let cells = framesOf(keyed, cellPitchFor(source)).map((cell) => dropCastShadow(cell));

    /**
     * **Ping-pong: play the poses out and back, so the wrap is a real step by construction.**
     *
     * Requested for `idle` in `character-bounds.json`, and it is an animation-design statement
     * rather than a workaround for a bad sheet. A breathing loop genuinely IS a there-and-back —
     * the chest rises and falls through the same positions — while a walk cycle is not, because
     * a reversed stride is a character moonwalking. So this is opt-in per animation, never
     * automatic, and never applied because a gate went red.
     *
     * It is also the fix that works. The regenerated 8-pose idle failed `gateLoopWrap` with a wrap
     * of 0.0356 against a 0.0152 budget, and no shorter prefix closed either: measured back to
     * frame 1, frames 5 through 8 all sit 0.037-0.038 away, so the model drifted off the neutral
     * pose partway through and never returned. Re-rolling is a coin flip on a model STYLE.md §3
     * records as NOT seed-deterministic. Mirroring is deterministic and free, and it is exactly
     * what `mirrorLoop` already does for the parallax seams — which went FAIL -> PASS on the same
     * reasoning.
     *
     * Interior frames only (`1..n` then `n-1..2`), so neither endpoint is duplicated and every
     * step in the loop is a step the artist actually drew.
     */
    if (config.animations?.[action]?.pingPong) {
      cells = [...cells, ...cells.slice(1, -1).reverse()];
    }

    /**
     * The SHEET's contact frame lands on the last row of its cell; the rest keep their lift.
     *
     * `playerView` draws at origin (0.5, 1) on the player's feet position and PLAYER_BOX is
     * authored +y up from the feet (vault 2.10), so a gap below the *contact* frame's feet would
     * sink the character into the ground by that many pixels. A gap below any OTHER frame is not a
     * defect — it is the trailing boot lifting, or the flight phase — and re-zeroing it per frame
     * is what made the torso sink while the legs pumped. See `sheets.mjs`'s header.
     */
    const anchor = config.animations?.[action]?.verticalAnchor ?? 'feet';

    /**
     * **Per-(slug, action) scale override, resolved here.**
     *
     * Padding is a property of a GENERATION, not of a subject, so the scale it implies is too — a
     * padded and an unpadded generation of the same character cannot share one number (session 6,
     * `brass-courier/attack` drew 114px against `hurt`'s 288px on the slug default). An action MAY
     * declare its own `scale` in `character-bounds.json`'s `animations[action]`; everything else
     * falls back to the slug default, unchanged from before this override existed.
     *
     * `scaleSource` travels with the number into the lift profile so `catalogWrite.mjs`'s guard
     * knows which entries the one-scale rule (vault A5) still binds — see that file's header for
     * why the rule now applies only to `scaleSource: 'slug'` entries (user decision D2, 2026-08-12).
     */
    /**
     * `null` is NOT an override — it is this project's "not measured yet" convention, the same one
     * `stridePxPerCycle` uses. Testing `!== undefined` treated it as one, so `"scale": null` resolved
     * to the SLUG's number and was then labelled `'action'`, silently exempting it from the one-scale
     * rule it should still be bound by. Found by the Codex implementation review, session 7.
     */
    const { scale: resolvedScale, scaleSource } = resolveActionScale(config, action);
    if (!(resolvedScale > 0)) {
      throw new Error(
        `assets:build: "${action}" resolved to a non-positive scale (${resolvedScale}) — check ` +
          `animations.${action}.scale in ${CONFIG}.`,
      );
    }

    const { strip, frames, deepestSourceY } = packStrip(cells, {
      scale: resolvedScale,
      frameWidth,
      frameHeight,
      baselineY: frameHeight,
      anchor,
    });

    const tallest = Math.max(...frames.map((f) => f.drawnHeight));
    const widest = Math.max(...frames.map((f) => f.drawnWidth));
    if (tallest > frameHeight || widest > frameWidth) {
      throw new Error(
        `assets:build: "${action}" needs ${widest}x${tallest} but the cell is ` +
          `${frameWidth}x${frameHeight}. Enlarge the cell in ${CONFIG} — do NOT rescale one ` +
          `animation to fit, which is exactly what vault 4.14 forbids.`,
      );
    }

    /**
     * **No cell may be blank or a fragment**, checked before the gates rather than by them.
     *
     * This exists because it happened: `detectFrames`'s fixed 8 px `minGap` segmented a swinging
     * arm as its own column band on the much larger video frames, so `walk` packed 15 cells for 12
     * sampled frames with **three of them empty**, and `fall` 7 for 6. Every gate passed it —
     * `gateMotionFloor` and `gateLoopWrap` are difference metrics, and a blank frame is a large,
     * perfectly consistent difference. On screen it is a character vanishing for a frame.
     *
     * A gate that cannot see a blank frame is decoration *(C2)*, and the honest fix is a check that
     * asks the question directly. The height test catches the near-miss too: a cell holding only a
     * detached boot is not empty, but it is not a frame either.
     */
    /**
     * 🔴 **The fragment test measures AREA, not height, and the difference is a death animation.**
     *
     * It used to compare `drawnHeight` against half the median height. That is a sound proxy for a
     * walk cycle, where every pose is the same height, and it is simply WRONG for a collapse: a
     * dying figure ends up lying down. `rust-scavenger/death` packs its corpse at **476x109**
     * against a median of 241 and was rejected as a fragment — and `character-bounds.json` already
     * records the same shape for the courier, whose ten death frames fall `476,428,358,228,240,
     * 220,142,106,106,106`, a 153 % spread. Any height rule rejects both.
     *
     * Opaque AREA survives a collapse, because the figure does not lose pixels by toppling — it
     * redistributes them. Measured on the real sheets: `rust-scavenger/death` spans **0.89-1.49x**
     * its median area across all ten frames, and `walk` **0.91-1.03x**. A genuine fragment is three
     * orders of magnitude away — the 36x9 chunk that first exposed this is ~0.003x. So a quarter of
     * the median separates them with enormous margin in both directions.
     *
     * This changes WHAT the check measures, never what it tolerates: it still fails a fragment, and
     * it now stops failing a legitimate pose. `f.pixels` is the opaque count `figureMetrics`
     * already returns, so nothing new is measured to get it.
     */
    const areas = frames.map((f) => f.pixels);
    const medianArea = [...areas].sort((a, b) => a - b)[areas.length >> 1];
    frames.forEach((f, i) => {
      if (f.drawnHeight <= 0 || f.drawnWidth <= 0) {
        throw new Error(
          `assets:build: "${action}" packed an EMPTY cell at index ${i} of ${frames.length}. ` +
            `That is a blank frame in the animation. It means the sheet segmented into more bands ` +
            `than there are figures — usually a limb split off by detectFrames' minGap.`,
        );
      }
      if (f.pixels < medianArea / 4) {
        throw new Error(
          `assets:build: "${action}" cell ${i} of ${frames.length} draws ${f.pixels} opaque px ` +
            `against a median of ${medianArea} — that is a fragment, not a frame. Same cause as an ` +
            `empty cell, caught one step earlier. (Measured as AREA on purpose: a collapsing ` +
            `figure loses HEIGHT legitimately, so a height rule rejects every death animation.)`,
        );
      }
    });

    // Gate the packed frames before writing them, not after — a sheet that fails its motion floor
    // should be visible at build time, not discovered in the Gym.
    const perFrame = frames.map((_, i) => sliceFrame(strip, i, frameWidth, frameHeight));
    const repeat = ACCEPTED_POSE_REPEATS[`${SLUG}/${action}`] ?? null;
    const verdicts = { motion: gateMotionFloor(perFrame), adjacent: gateAdjacentDistinct(perFrame, undefined, repeat) };
    if (LOOPING.has(action)) {
      verdicts.loop = gateLoopWrap(perFrame);
    }
    const summary = summarise(verdicts);

    const out = join(OUT_DIR, `${action}.png`);
    writeFileSync(out, encodePng(strip.width, strip.height, strip.data));

    rows.push(
      sheetReportRow({
        slug: SLUG,
        action,
        frameWidth,
        frameHeight,
        frameCount: frames.length,
        loop: LOOPING.has(action),
        key,
        agreement,
        tallest,
        widest,
        verdicts,
        summary: summary.status,
      }),
    );

    // 🔴 The decision is `catalogDecision.mjs`'s, not this file's. It used to be a bare
    // `if (hasCatalogTiming(...))` with **no else**, and because `upsertCatalogSheets` leaves keys
    // it was not handed untouched, a sheet rebuilt without a timing rule kept shipping the catalog
    // row describing its PREVIOUS self. That bit `brass-courier/idle` in play, and the Codex plan
    // review (finding 2) rejected "log a warning" as a fix for it. It fails the build now.
    if (
      decideCatalogRow({
        slug: SLUG,
        action,
        hasTiming: hasCatalogTiming(SLUG, action),
        hasExistingRow: existingCatalogKeys.has(`${SLUG}-${action}`),
      }) === 'write'
    ) {
      catalogRows.push(
        catalogRowFor(
          SLUG,
          action,
          {
            url: `assets/characters/${SLUG}/sheets/${action}.png`,
            frameWidth,
            frameHeight,
            frameCount: frames.length,
          },
          // Authored cadence + the packed frame count, not a stride (session 9). A looping
          // animation's rate is now a number a human set by watching the character; see
          // `catalogTimings.mjs`'s AUTHORED_LOOPS note for what deriving it from a measured stride
          // actually cost. `frames.length` is the count the packer just wrote, so the cadence and
          // the sheet cannot disagree about how many frames there are.
          {
            authoredFps: config.animations?.[action]?.fps,
            renderFrames: frames.length,
          },
        ),
      );
    }

    liftProfile[action] = liftProfileEntry({
      anchor,
      scale: resolvedScale,
      scaleSource,
      deepestSourceY,
      frames,
    });

    const flag = summary.status === PASS ? 'ok  ' : '⚠   ';
    console.log(
      `${flag}${action.padEnd(5)} ${frames.length} frames  ${frameWidth}x${frameHeight}  ` +
        `drawn ${widest}x${tallest}  key(${key.join(',')})  ${summary.status}`,
    );
    for (const [name, v] of Object.entries(verdicts)) {
      console.log(`      ${name}: ${v.status} — ${v.reason}`);
    }
  }

  writeFileSync(REPORT_PATH, `${JSON.stringify(rows, null, 2)}\n`);

  /**
   * The lift-profile manifest — the only INDEPENDENT oracle criterion 4.19 can have.
   *
   * Codex plan review, blocker 2. A packed PNG cannot reveal its own pre-pack source lift, and
   * `_generated/` is gitignored, so a test on a clean clone has no access to the clips. Deriving the
   * expectation from the packed strip would be tautological — it would pass against per-frame
   * anchoring too, which is the exact defect being guarded.
   *
   * So this file carries the SOURCE coordinates: each frame's `sourceMaxY` and the sheet's
   * `deepestSourceY`, both measured before packing. `tests/unit/sheet-packing.test.ts` re-derives
   * `round((deepest - sourceMaxY) * scale)` from those numbers — checking the packer's arithmetic
   * rather than trusting it — and then measures the shipped PNG's actual gap below the feet and
   * requires the two to agree EXACTLY. A per-frame regression puts every measured gap at 0 while
   * this file still says otherwise, and the gate goes red.
   *
   * Its ceiling, stated: regenerating the art rewrites this alongside the strips, so it cannot
   * catch a bad regeneration by itself. It is committed and carries its inputs precisely so the
   * lift profile is reviewable in a diff when that happens.
   */
  upsertLiftProfile(LIFT_PROFILE, {
    comment: LIFT_PROFILE_NOTE,
    slug: SLUG,
    scale,
    animations: liftProfile,
  });

  let catalogNote = '';
  if (catalogRows.length > 0) {
    // Measured from the PNG bytes actually on disk, decoded independently — NOT from the numbers
    // the packer was handed. The obvious version of this check read its expectation from the thing
    // it was checking and could not fail (Codex plan review, finding 4).
    validateCatalogRows(catalogRows, (row) => {
      const png = decodePng(readFileSync(join('public/assets', row.url.replace(/^assets\//, ''))));
      return { width: png.width, height: png.height };
    });
    // One upsert for the whole run, not one per action — a single read-merge-write.
    upsertCatalogSheets(CATALOG_PATH, catalogRows);
    catalogNote = ` and ${catalogRows.length} row(s) into ${CATALOG_PATH}`;
  }
  console.log(
    `\nwrote ${rows.length} strips to ${OUT_DIR}, ${REPORT_PATH} and ${LIFT_PROFILE}${catalogNote}`,
  );
}

main();
